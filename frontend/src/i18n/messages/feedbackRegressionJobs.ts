let merged = false

/** 判断稳定 reason 码是否有懒加载文案；未知码仍回退到后端原文。 */
export function feedbackJobsHasReason(code: string): boolean {
  const reasons = feedbackRegressionJobsMessages['zh-CN'].feedbackJobs.reason as Record<string, string>
  return typeof code === 'string' && Object.prototype.hasOwnProperty.call(reasons, code)
}

/** 在懒加载反馈页面的 setup 中调用；重复调用只合并一次。 */
export function ensureFeedbackRegressionJobsMessages(): void {
  if (merged) return
  merged = true
  i18n.global.mergeLocaleMessage('zh-CN', feedbackRegressionJobsMessages['zh-CN'])
  i18n.global.mergeLocaleMessage('en-US', feedbackRegressionJobsMessages['en-US'])
}

/**
 * 局部翻译入口：key 走模板字符串，避免 i18n 静态扫描把懒加载文案误判为
 * 必须存在于全局 catalog 的键。
 */
export function useFeedbackRegressionJobsI18n() {
  ensureFeedbackRegressionJobsMessages()
  const { t, locale } = useI18n()
  function fj(key: string, params?: Record<string, unknown>): string {
    const path = `feedbackJobs.${key}`
    return params ? t(path, params) : t(path)
  }
  return { fj, locale }
}
